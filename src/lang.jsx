export const LangContext = createContext({ lang: "en", t: (k) => k });
export const useLang = () => useContext(LangContext);

export function makeT(lang) {
  return (key, vars = {}) => {
    const s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  };
}
